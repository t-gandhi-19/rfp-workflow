"""The externally-authored answer key — independent ground truth for extraction.

`fixtures/answer_key_manual.json` is authored **independently of the extraction
pipeline and of the fixture source**: by reading the rendered PDF, with match
picks derived from `qa_pairs.json` question texts only — never from
`golden_rfp_source.json` and never from the generated `answer_key.json`.

That independence is the entire point. `golden_rfp_source.json` and the extractor
share an ancestor, so comparing those two measures internal consistency rather
than correctness. This file is the one ground truth here that does not.

**The builder never edits, regenerates, or "corrects" this file** — not for a
failing eval, not for a typo, not on request mid-session. The code here loads it,
validates its structure, and cross-references ids against the corpus. It does not
compare the key against `golden_rfp_source.json`, and it never writes to it.

If the key and the extractor disagree, the disagreement is a finding to be
surfaced with an analysis of which side is right. Where the extractor is wrong,
the extractor is fixed. Where the key is wrong, the finding says so and the
project owner decides; a correction lands only after explicit review approval.
Silently reconciling either way would destroy the only independent measurement
there is.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from pydantic import BaseModel, ConfigDict, Field, model_validator

REPO_ROOT = Path(__file__).resolve().parents[2]
FIXTURES = REPO_ROOT / "fixtures"
MANUAL_KEY_PATH = FIXTURES / "answer_key_manual.json"
SCHEMA_PATH = FIXTURES / "answer_key_manual.schema.json"

#: Shown wherever the key is required but absent. Names the phase section that
#: explains what the file is and who writes it.
MISSING_MESSAGE = (
    "manual key missing — see §4\n"
    f"  expected at: {MANUAL_KEY_PATH.relative_to(REPO_ROOT)}\n"
    "  This file is externally authored, independent of the extraction\n"
    "  pipeline and of the fixture source. It is the independent ground truth\n"
    "  for the extraction evals and is never generated by tooling, so the\n"
    "  extraction evals cannot run without it.\n"
    "  Structure: fixtures/answer_key_manual.schema.json\n"
    "  Validate with: make validate-manual-key"
)


class MissingManualKeyError(FileNotFoundError):
    """Raised when the extraction evals are run without the externally-authored key."""


class ManualQuestion(BaseModel):
    """One question as read off the rendered document."""

    model_config = ConfigDict(extra="forbid")

    #: Zero-based position in the document, in reading order.
    order: int = Field(ge=0)
    #: The printed number, e.g. "2.3".
    number: str = Field(min_length=1)
    #: The section heading it appeared under.
    section: str = Field(min_length=1)
    #: The question as printed, without the numbering or the bracketed
    #: annotation. Whitespace is normalised on load, so line wrapping in the PDF
    #: does not count as a disagreement.
    text: str = Field(min_length=1)
    mandatory: bool
    word_limit: int | None = Field(default=None, gt=0)
    #: Optional. When present, cross-referenced against the corpus by
    #: `make validate-manual-key`.
    expected_best_match_answer_id: str | None = None
    #: Free-text note from the author, e.g. why a question was read a given way.
    note: str | None = None

    @model_validator(mode="after")
    def _normalise_text(self) -> ManualQuestion:
        object.__setattr__(self, "text", " ".join(self.text.split()))
        return self


class ManualAnswerKey(BaseModel):
    """The whole externally-authored key."""

    model_config = ConfigDict(extra="forbid")

    #: Which document was read. Recorded so a key written against an older
    #: rendering is identifiable rather than silently misleading.
    source_document: str = Field(min_length=1)
    rfp_reference: str = Field(min_length=1)
    issuer: str = Field(min_length=1)
    deadline: str | None = None
    authored_by: str = Field(min_length=1)
    authored_on: str = Field(min_length=1)
    questions: list[ManualQuestion] = Field(min_length=1)

    @model_validator(mode="after")
    def _orders_are_sequential_and_unique(self) -> ManualAnswerKey:
        orders = [question.order for question in self.questions]
        if len(set(orders)) != len(orders):
            raise ValueError("duplicate `order` values")
        if sorted(orders) != list(range(len(orders))):
            raise ValueError(
                f"`order` must be 0..{len(orders) - 1} with no gaps; got {sorted(orders)}"
            )
        return self

    @model_validator(mode="after")
    def _numbers_are_unique(self) -> ManualAnswerKey:
        numbers = [question.number for question in self.questions]
        if len(set(numbers)) != len(numbers):
            raise ValueError("duplicate question `number` values")
        return self

    def in_document_order(self) -> list[ManualQuestion]:
        return sorted(self.questions, key=lambda question: question.order)


def load_manual_key(path: Path | None = None) -> ManualAnswerKey:
    """Load and validate the externally-authored key.

    Raises :class:`MissingManualKeyError` with an actionable message when the
    file is absent, so an eval run says what to do rather than what broke.
    """
    resolved = path or MANUAL_KEY_PATH
    if not resolved.is_file():
        raise MissingManualKeyError(MISSING_MESSAGE)
    with resolved.open(encoding="utf-8") as handle:
        payload = json.load(handle)
    return ManualAnswerKey.model_validate(payload)


def manual_key_exists(path: Path | None = None) -> bool:
    return (path or MANUAL_KEY_PATH).is_file()


def json_schema() -> dict[str, Any]:
    """JSON Schema for the file, derived from the model so they cannot drift."""
    schema = ManualAnswerKey.model_json_schema()
    schema["$schema"] = "https://json-schema.org/draft/2020-12/schema"
    schema["title"] = "rfp-workflow manual answer key"
    schema["description"] = (
        "Externally-authored ground truth for the extraction evals, independent of the "
        "extraction pipeline and of the fixture source. Never generated or edited by the builder."
    )
    return schema


def cross_reference_errors(key: ManualAnswerKey, pairs: list[dict[str, Any]]) -> list[str]:
    """Check the key's answer ids against the corpus.

    Two rules, both about the key being *usable*, not about it agreeing with the
    extractor:

    * every referenced answer id exists
    * no referenced answer is superseded — expecting a superseded answer as a
      best match would contradict the staleness eval, which requires zero
      superseded answers surfaced
    """
    by_answer = {pair["answer_id"]: pair for pair in pairs}
    superseded = {pair["answer_id"] for pair in pairs if pair.get("superseded_by")}

    errors: list[str] = []
    for question in key.in_document_order():
        answer_id = question.expected_best_match_answer_id
        if answer_id is None:
            continue
        if answer_id not in by_answer:
            errors.append(
                f"question {question.number} (order {question.order}): "
                f"expected_best_match_answer_id '{answer_id}' is not in the corpus"
            )
            continue
        if answer_id in superseded:
            errors.append(
                f"question {question.number} (order {question.order}): "
                f"expected_best_match_answer_id '{answer_id}' is superseded by "
                f"'{by_answer[answer_id]['superseded_by']}'; retrieval must surface "
                "the replacement, and the staleness eval allows zero superseded answers"
            )
    return errors
